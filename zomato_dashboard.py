import streamlit as st
import mysql.connector
import pandas as pd
import time
from zomato_db_config import DB_CONFIG

# -------------------------------
# 1. Dashboard Configuration
# -------------------------------

st.set_page_config(
    page_title="Zomato Real-Time Analytics",
    page_icon="🍔",
    layout="wide"
)

st.title("🍔 Zomato Real-Time Food Delivery Analytics")
st.caption("Live order monitoring and business performance dashboard")

# -------------------------------
# 2. Connect to MySQL
# -------------------------------

def get_connection():
    return mysql.connector.connect(**DB_CONFIG)
# -------------------------------
# 3. Fetch Order Data
# -------------------------------

def load_data():

    connection = get_connection()

    query = """
    SELECT order_id, restaurant, amount,
           delivery_time_minutes, status, order_timestamp,
           is_anomaly, anomaly_score
    FROM orders
    ORDER BY order_timestamp DESC
"""
    df = pd.read_sql(query, connection)

    connection.close()

    return df

# -------------------------------
# 4. Load Dashboard Data
# -------------------------------

try:
    df = load_data()

    if df.empty:
        st.warning("Waiting for incoming orders...")
        st.stop()

    # -------------------------------
    # 5. Calculate KPIs
    # -------------------------------

    total_orders = len(df)
    total_revenue = df["amount"].sum()
    average_order_value = df["amount"].mean()
    average_delivery_time = df["delivery_time_minutes"].mean()

    # -------------------------------
    # 6. KPI Cards
    # -------------------------------

    st.subheader("📊 Business Overview")

    col1, col2, col3, col4 = st.columns(4)

    col1.metric("Total Orders", f"{total_orders:,}")
    col2.metric("Total Revenue", f"₹{total_revenue:,.2f}")
    col3.metric("Average Order Value", f"₹{average_order_value:,.2f}")
    col4.metric("Avg Delivery Time", f"{average_delivery_time:.1f} min")

    st.divider()

    # -------------------------------
    # 7. Restaurant Analytics
    # -------------------------------

    st.subheader("🍽️ Restaurant Performance")

    restaurant_data = (
        df.groupby("restaurant")["order_id"]
        .count()
        .reset_index(name="total_orders")
    )

    col1, col2 = st.columns(2)

    with col1:
        st.write("Orders by Restaurant")
        st.bar_chart(
            restaurant_data,
            x="restaurant",
            y="total_orders"
        )

    with col2:
        st.write("Revenue by Restaurant")

        revenue_data = (
            df.groupby("restaurant")["amount"]
            .sum()
            .reset_index()
        )

        st.bar_chart(
            revenue_data,
            x="restaurant",
            y="amount"
        )

    st.divider()

    # -------------------------------
    # 8. Order Status Analytics
    # -------------------------------

    st.subheader("📦 Order Status Distribution")

    status_data = (
        df.groupby("status")["order_id"]
        .count()
        .reset_index(name="count")
    )

    st.bar_chart(
        status_data,
        x="status",
        y="count"
    )

    st.divider()

    # -------------------------------
    # 9. Delivery Time Analytics
    # -------------------------------

    st.subheader("🚚 Delivery Time Analysis")

    delivery_data = (
        df.groupby("restaurant")["delivery_time_minutes"]
        .mean()
        .reset_index()
    )

    st.bar_chart(
        delivery_data,
        x="restaurant",
        y="delivery_time_minutes"
    )

    st.divider()

    # -------------------------------
    # 10. Latest Orders Table
    # -------------------------------

    st.subheader("🧾 Latest Orders")

    st.dataframe(
        df.head(20),
        use_container_width=True,
        hide_index=True
    )

    st.caption(f"Last refreshed: {time.strftime('%d-%m-%Y %H:%M:%S')}")

except Exception as e:
    st.error(f"Dashboard Error: {e}")

# -------------------------------
# 11. Automatic Refresh
# -------------------------------

# --------------------------------
# 12. MACHINE LEARNING ANOMALY DETECTION
# --------------------------------

st.divider()

st.header("🤖 Machine Learning - Anomaly Detection")

st.write(
    "Isolation Forest identifies unusual food orders "
    "based on order amount and delivery time. "
    "Predictions are generated by the live stream processor "
    "and stored in MySQL."
)

# Use predictions already stored in MySQL
df["anomaly_label"] = df["is_anomaly"].map({
    0: "Normal",
    1: "Anomaly"
})

# Calculate anomaly statistics
total_anomalies = int((df["is_anomaly"] == 1).sum())
normal_orders = int((df["is_anomaly"] == 0).sum())

total_processed = total_anomalies + normal_orders

if total_processed > 0:

    anomaly_percentage = (
        total_anomalies / total_processed
    ) * 100

    # Display ML metrics
    col1, col2, col3 = st.columns(3)

    col1.metric("Total Anomalies", total_anomalies)
    col2.metric("Normal Orders", normal_orders)

    col3.metric(
        "Anomaly Percentage",
        f"{anomaly_percentage:.2f}%"
    )

    # Anomaly distribution chart
    st.subheader("Anomaly Distribution")

    anomaly_summary = pd.DataFrame({
        "Order Type": ["Normal", "Anomaly"],
        "Count": [normal_orders, total_anomalies]
    })

    st.bar_chart(
        anomaly_summary,
        x="Order Type",
        y="Count"
    )

    # Display flagged orders
    st.subheader("🚨 Detected Unusual Orders")

    anomalies = df[df["is_anomaly"] == 1].copy()

    if not anomalies.empty:

        st.dataframe(
            anomalies[[
                "order_id",
                "restaurant",
                "amount",
                "delivery_time_minutes",
                "status",
                "anomaly_score"
            ]],
            use_container_width=True,
            hide_index=True
        )

    else:
        st.success("No unusual orders detected.")

else:
    st.warning("No processed anomaly predictions available.")
# --------------------------------
# 13. AUTOMATIC REFRESH
# --------------------------------

time.sleep(5)
st.rerun()